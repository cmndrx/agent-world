const cache = {};
/** Inline SVG markup for an icon, sized by CSS (1em by default). */
export function icon(name, cls = '') {
  const key = `${name}|${cls}`;
  if (!cache[key]) {
    const raw = RAW[name] || RAW.sparkles;
    cache[key] = raw
      .replace(/<!--.*?-->/s, '')
      .replace(/class="[^"]*"/, `class="icon${cls ? ` ${cls}` : ''}" aria-hidden="true"`)
      .replace(/width="24"\s*height="24"/, '')
      .replace(/\s+/g, ' ')
      .trim();
  }
  return cache[key];
}

